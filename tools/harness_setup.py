# Migrations replayed to build the harness schema, in order.
# Read from the directory rather than listed here. This was a hand-kept list,
# and when migration 0012 arrived the harness simply did not have the new
# table: every suite that touched it failed with "no such table", which looks
# like a bug in the feature rather than a stale list. The seed database is
# already at 0001, so that one is skipped.
#
# Sorted by filename, which is the revision order because every migration is
# named NNNN_*. A migration that broke that convention would be applied out of
# order here, so keep the numbering.
def _migrations():
    d = PROJECT / "alembic" / "versions"
    names = sorted(p.name for p in d.glob("[0-9][0-9][0-9][0-9]_*.py"))
    return [n for n in names if not n.startswith("0001_")]


MIGRATIONS = _migrations()

