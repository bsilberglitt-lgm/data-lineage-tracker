def generate_one(name):
    """The generated DDL for a single migration."""
    path = PROJECT / "alembic" / "versions" / name
    if not path.exists():
        return ""
    result = subprocess.run(
        [sys.executable, str(PROJECT / "tools" / "gen_harness_schema.py"), str(path)],
        capture_output=True, text=True, check=True)
    body = result.stdout.strip()
    return f"# ---- {name} ----\n{body}\n" if body else ""


def generate_ddl():
    """Run the schema generator over every migration after 0001, in order."""
    out = []
    for name in MIGRATIONS:
        if name == FIRST_MIGRATION:
            continue
        path = PROJECT / "alembic" / "versions" / name
        if not path.exists():
            continue
        result = subprocess.run(
            [sys.executable, str(PROJECT / "tools" / "gen_harness_schema.py"), str(path)],
            capture_output=True, text=True, check=True)
        body = result.stdout.strip()
        if body:
            out.append(f"# ---- {name} ----")
            out.append(body)
    text = "\n".join(out)
    # Composite primary keys are handled by gen_harness_schema.py itself now;
    # this used to carry a hand-written replacement for scenario_member, which
    # silently did nothing the moment a second such table arrived.
    return text


def main():
    HARNESS.mkdir(parents=True, exist_ok=True)
    (HARNESS / "static").mkdir(exist_ok=True)
    (HARNESS / "tools").mkdir(exist_ok=True)

    src = PROJECT / "tools" / "harness" / "fakelibs"
    dst = HARNESS / "fakelibs"
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)

    for name in APP_FILES:
        p = PROJECT / name
        if p.exists():
            shutil.copy(p, HARNESS / name)
    # Schema seed files are GLOBBED rather than listed, because `seed_schema()`
    # globs them too — a hand-kept list here would mean the harness quietly
    # not having a schema to drill into. Which is exactly what happened the
    # first time: `sample_schema.json` was not in APP_FILES, so schema_table
    # came up empty and selftest's governance-inheritance checks had nothing
    # to inherit through. The suites do not say "no schema was seeded"; they
    # say an assertion about governance failed.
    for p in PROJECT.glob("*_schema.json"):
        shutil.copy(p, HARNESS / p.name)
    shutil.copy(PROJECT / "static" / "index.html", HARNESS / "static" / "index.html")
    help_dir = PROJECT / "static" / "help"
    if help_dir.exists():
        target = HARNESS / "static" / "help"
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(help_dir, target)
    for tool in ["scenario_walkthrough.py"]:
        p = PROJECT / "tools" / tool
        if p.exists():
            shutil.copy(p, HARNESS / "tools" / tool)

    # The focused suites live in the repo so a sandbox reset cannot take them.
    tests = PROJECT / "tools" / "tests"
    if tests.exists():
        for p in tests.glob("t_*.py"):
            shutil.copy(p, HARNESS / p.name)

    # 0001 first, because the hand-written 0002 block in PREAMBLE renames the
    # table 0001 creates. Everything after 0001 follows.
    reset = (PREAMBLE.format(db=str(HARNESS / "test.db"))
             + generate_one(FIRST_MIGRATION)
             + PRELUDE_0002
             + generate_ddl() + POSTAMBLE)
    (HARNESS / "reset_db.py").write_text(reset)

    print(f"harness built at {HARNESS}")
    print("  next:  cd {0} && python3 reset_db.py".format(HARNESS))
    print("  run:   PYTHONPATH={0}/fakelibs FAKE_SQLITE={0}/test.db \\\n"
          "         DATABASE_URL=postgresql://fake/fake PORT=8900 \\\n"
          "         BOOTSTRAP_SUPERADMIN_EMAIL=you@example.gov \\\n"
          "         BOOTSTRAP_SUPERADMIN_PASSWORD='Bootstrap-Temp-7xQ!' \\\n"
          "         python3 app.py".format(HARNESS))


if __name__ == "__main__":
    main()
