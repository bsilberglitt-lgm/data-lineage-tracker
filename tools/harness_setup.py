#!/usr/bin/env python3
"""Build the sandbox test harness at /tmp/h2, from scratch.

The assistant's sandbox has no PostgreSQL, no Docker and no package installs,
so the app is exercised against SQLite through a fake driver. That harness used
to be assembled by hand and lived only in /tmp, which meant losing it whenever
the sandbox was reset — twice so far, each time costing a rebuild from memory
and, once, a subtly wrong fake driver.

Everything it needs is now in the repository:

    tools/harness/fakelibs/     the fake psycopg pool and no-op alembic
    tools/gen_harness_schema.py DDL generated from the real migrations
    lineage.db                  the pre-auth seed database

Run it after any sandbox reset, or after adding a migration:

    python3 tools/harness_setup.py
    cd /tmp/h2 && python3 reset_db.py

**The schema is generated from alembic/versions/, not written by hand**, so the
harness cannot quietly disagree with production about a column. What it still
cannot prove is anything PostgreSQL-specific: partial indexes, collation,
concurrent access, and real foreign-key behavior under load. Those need
`docker compose up` and the click-through.
"""

