def add(table, coldef):
    """ALTER ... ADD COLUMN, tolerating a column that is already present.

    The generator emits each migration's own add_column calls; the blocks below
    cover the ones written as Python loops, which it cannot see. Overlap is
    expected and harmless."""
    try:
        x(f"ALTER TABLE {{table}} ADD COLUMN {{coldef}}")
    except sqlite3.OperationalError as e:
        if "duplicate column" not in str(e):
            raise


